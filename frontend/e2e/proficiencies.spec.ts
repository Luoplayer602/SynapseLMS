  await page.getByRole('link', { name: 'Hồ sơ học viên của tôi' }).click()
  await page.getByRole('button', { name: 'Trình độ và mục tiêu', exact: true }).click()
  await page.getByRole('combobox', { name: 'Ngôn ngữ đào tạo', exact: true }).selectOption({ label: 'Ngôn ngữ trình độ demo (PF-EN)' })
  await page.getByRole('combobox', { name: 'Bộ cấp độ', exact: true }).selectOption({ label: 'Bộ trình độ demo (PF-SCALE)' })

  await expect(page.getByText('Trung tâm xác nhận: Chưa có xác nhận hiện hành', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Lịch sử trình độ/mục tiêu', exact: true }).click()
  await expect(page.getByRole('heading', { name: /Thu hồi xác nhận · v/ })).toBeVisible()
  await expect(page.getByText(/PRIVATE-PF/)).toHaveCount(0)
  await page.getByRole('button', { name: 'English', exact: true }).click()

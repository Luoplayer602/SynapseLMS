  await create('/members', { email: 'pf-staff@example.com', display_name: 'PF Staff', password: 'proficiency-test-password!', role: 'staff', reason: 'E2E fixture' })
  await create('/students', { user_id: student.user_id, full_name: 'PF Learner' })

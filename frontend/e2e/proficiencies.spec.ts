  await page.getByRole('combobox', { name: 'Trình độ tự khai', exact: true }).selectOption({ label: 'Mức một demo (PF-L1)' })
  await page.getByRole('button', { name: 'Lưu tự khai', exact: true }).click()
  await expect(page.getByText('Trình độ tự khai: Mức một demo', { exact: false })).toBeVisible()
  await page.getByRole('textbox', { name: 'Mục tiêu học', exact: true }).fill('Ôn giao tiếp cơ bản')
  await page.getByRole('combobox', { name: 'Cấp độ mong muốn', exact: true }).selectOption({ label: 'Mức một demo (PF-L1)' })
  await page.getByRole('button', { name: 'Lưu mục tiêu', exact: true }).click()
  await expect(page.getByText('Mục tiêu học: Ôn giao tiếp cơ bản', { exact: true })).toBeVisible()
  const staffContext = await browser.newContext({ baseURL: 'http://127.0.0.1:5180' })
  const staff = await staffContext.newPage()
  await signIn(staff, 'pf-staff@example.com')
  await staff.getByRole('link', { name: 'Học viên', exact: true }).click()
  await staff.getByLabel('Tìm theo mã hoặc tên học viên').fill('PF Learner')
  await staff.getByRole('button', { name: 'Tìm kiếm', exact: true }).click()
  await staff.getByRole('button', { name: 'Xem hồ sơ', exact: true }).click()
  await staff.getByRole('button', { name: 'Trình độ và mục tiêu', exact: true }).click()
  await staff.getByRole('button', { name: 'Xem trình độ và mục tiêu', exact: true }).click()
  await staff.getByRole('button', { name: 'Xác nhận/điều chỉnh trình độ', exact: true }).click()
  await staff.getByRole('combobox', { name: 'Cấp độ được xác nhận', exact: true }).selectOption({ label: 'Mức hai demo (PF-L2)' })
